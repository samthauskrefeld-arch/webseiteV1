/**
 * Generates the full PostgreSQL DDL that corresponds to prisma/schema.prisma
 * (Prisma naming conventions). Used to
 *   1. create the initial migration in environments where Prisma's native schema engine
 *      cannot be downloaded (binaries.prisma.sh blocked), and
 *   2. detect drift: `pnpm db:check-drift` applies this DDL to a scratch database and compares
 *      it to the database produced by the migrations.
 * In environments with full internet access, `prisma migrate dev` can be used instead.
 *
 * Usage: node scripts/schema-to-sql.mjs prisma/schema.prisma > out.sql
 */
import internals from "@prisma/internals";
import fs from "node:fs";

const schemaPath = process.argv[2] ?? "prisma/schema.prisma";
const { datamodel } = await internals.getDMMF({ datamodel: fs.readFileSync(schemaPath, "utf8") });

const q = (s) => `"${s}"`;
const scalarSql = (f) => {
  const native = f.nativeType?.[0];
  let t;
  switch (f.type) {
    case "String":
      t = native === "Uuid" ? "UUID" : "TEXT";
      break;
    case "Int":
      t = "INTEGER";
      break;
    case "BigInt":
      t = "BIGINT";
      break;
    case "Float":
      t = "DOUBLE PRECISION";
      break;
    case "Boolean":
      t = "BOOLEAN";
      break;
    case "DateTime":
      t = native === "Date" ? "DATE" : "TIMESTAMP(3)";
      break;
    case "Json":
      t = "JSONB";
      break;
    default:
      t = q(f.type); // enum
  }
  return f.isList ? `${t}[]` : t;
};
const defaultSql = (f) => {
  if (!f.hasDefaultValue || f.default === undefined) return "";
  const d = f.default;
  if (typeof d === "object" && !Array.isArray(d) && d !== null) {
    if (d.name === "now") return " DEFAULT CURRENT_TIMESTAMP";
    return ""; // uuid()/cuid() are generated by the client
  }
  if (typeof d === "string") {
    if (f.kind === "enum") return ` DEFAULT '${d}'`;
    if (f.type === "Json") return ` DEFAULT '${d.replace(/'/g, "''")}'`;
    return ` DEFAULT '${d.replace(/'/g, "''")}'`;
  }
  if (typeof d === "boolean" || typeof d === "number") return ` DEFAULT ${d}`;
  return "";
};

const out = [];
for (const e of datamodel.enums) {
  out.push(`-- CreateEnum\nCREATE TYPE ${q(e.name)} AS ENUM (${e.values.map((v) => `'${v.name}'`).join(", ")});\n`);
}
const fks = [];
const idx = [];
for (const m of datamodel.models) {
  const cols = [];
  for (const f of m.fields) {
    if (f.kind === "object") {
      if (f.relationFromFields?.length) {
        const name = `${m.name}_${f.relationFromFields.join("_")}_fkey`;
        const onDelete = (f.relationOnDelete ?? (f.isRequired ? "Restrict" : "SetNull")).replace(/([a-z])([A-Z])/g, "$1 $2").toUpperCase();
        fks.push(
          `-- AddForeignKey\nALTER TABLE ${q(m.name)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${f.relationFromFields.map(q).join(", ")}) REFERENCES ${q(f.type)}(${f.relationToFields.map(q).join(", ")}) ON DELETE ${onDelete} ON UPDATE CASCADE;\n`,
        );
      }
      continue;
    }
    cols.push(`    ${q(f.dbName ?? f.name)} ${scalarSql(f)}${f.isRequired && !f.isList ? " NOT NULL" : ""}${defaultSql(f)}`);
  }
  const idFields = m.primaryKey?.fields ?? m.fields.filter((f) => f.isId).map((f) => f.name);
  cols.push(`\n    CONSTRAINT ${q(`${m.name}_pkey`)} PRIMARY KEY (${idFields.map(q).join(",")})`);
  out.push(`-- CreateTable\nCREATE TABLE ${q(m.name)} (\n${cols.join(",\n")}\n);\n`);
}
for (const i of datamodel.indexes) {
  if (i.type === "id") continue;
  const fields = i.fields.map((f) => f.name);
  const name = i.dbName ?? `${i.model}_${fields.join("_")}_${i.type === "unique" ? "key" : "idx"}`;
  idx.push(`-- CreateIndex\nCREATE ${i.type === "unique" ? "UNIQUE " : ""}INDEX ${q(name)} ON ${q(i.model)}(${fields.map(q).join(", ")});\n`);
}
process.stdout.write([...out, ...idx, ...fks].join("\n"));
